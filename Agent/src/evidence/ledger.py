"""
Step 12 - Evidence Ledger (§B11, §B12).
Maintains an immutable ledger of every claim, figure, confidence interval,
and evidence grade (0 to 4) generated by queries and analytical modules.
"""
from typing import List, Dict, Any, Optional
from src.models.schemas import EvidenceClaim, EvidenceLedger
from src.config import EVIDENCE_GRADES


class LedgerManager:
    """Manages recording and querying evidence claims."""

    def __init__(self):
        self.ledger = EvidenceLedger()

    def record_claim(
        self,
        text: str,
        grade: int,
        source_type: str,
        source_id: str,
        data: Optional[Dict[str, Any]] = None
    ) -> EvidenceClaim:
        """Adds a claim to the ledger with its assigned evidence grade."""
        grade_desc = EVIDENCE_GRADES.get(grade, "Unknown")
        payload = data or {}
        payload["grade_description"] = grade_desc
        return self.ledger.add_claim(text, grade, source_type, source_id, payload)

    def get_claims(self) -> List[EvidenceClaim]:
        return self.ledger.claims

    def extract_numbers_summary(self) -> List[str]:
        """Extracts text of all recorded claims for fact-checking."""
        return [c.text for c in self.ledger.claims]
